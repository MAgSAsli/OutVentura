  nama varchar(100) not null,
  email varchar(150) not null unique,
  password varchar(255) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================
-- TABLE: alat / rental items
-- =========================
create table public.alat (
  id bigint generated by default as identity primary key,
  nama_alat varchar(100) not null,
  kategori varchar(50) not null,
  harga integer not null check (harga >= 0),
  stok integer not null default 0 check (stok >= 0),
  deskripsi text,
  gambar text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================
-- TABLE: transaksi / rental transaction
-- Status lama dipertahankan agar cocok dengan kode sekarang:
-- pending, lunas, selesai, batal
-- Status payment/rental disiapkan untuk pengembangan berikutnya:
-- pending_payment, paid, dipinjam, expired
-- =========================
create table public.transaksi (
  id bigint generated by default as identity primary key,
  id_penyewa bigint not null references public.penyewa(id) on update cascade on delete restrict,
  id_pegawai bigint references public.pegawai(id) on update cascade on delete set null,
  tanggal_transaksi date not null default current_date,
  tanggal_mulai date not null,
  tanggal_selesai date not null,
  jumlah_hari integer generated always as (tanggal_selesai - tanggal_mulai) stored,
  total_harga integer not null default 0 check (total_harga >= 0),
  status varchar(30) not null default 'pending' check (
    status in (
      'pending',
      'lunas',
      'selesai',
      'batal',
      'pending_payment',
      'paid',
      'dipinjam',
      'expired'
    )
  ),

  -- Kolom opsional untuk integrasi payment gateway seperti Midtrans nanti.
  payment_order_id varchar(100) unique,
  payment_token text,
  payment_redirect_url text,
  payment_method varchar(50),
  paid_at timestamptz,

  -- Kolom opsional untuk fitur pengembalian dan denda.
  tanggal_kembali date,
  denda integer not null default 0 check (denda >= 0),

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint transaksi_tanggal_valid check (tanggal_selesai > tanggal_mulai)
);

-- =========================
-- TABLE: detail_transaksi
-- =========================
create table public.detail_transaksi (
  id bigint generated by default as identity primary key,
  id_transaksi bigint not null references public.transaksi(id) on update cascade on delete cascade,
  id_alat bigint not null references public.alat(id) on update cascade on delete restrict,
  jumlah integer not null check (jumlah > 0),
  harga_satuan integer not null check (harga_satuan >= 0),
  subtotal integer not null check (subtotal >= 0),
  created_at timestamptz not null default now()
);

