-- =========================
-- View untuk riwayat transaksi mirip query MySQL GROUP_CONCAT
-- =========================
create or replace view public.vw_riwayat_transaksi as
select
  t.*,
  string_agg(a.nama_alat, ', ' order by a.nama_alat) as nama_alat_list
from public.transaksi t
left join public.detail_transaksi dt on dt.id_transaksi = t.id
left join public.alat a on a.id = dt.id_alat
group by t.id;

-- =========================
-- View dashboard laporan bulanan
-- =========================
create or replace view public.vw_laporan_bulanan as
select
  extract(year from tanggal_transaksi)::int as tahun,
  extract(month from tanggal_transaksi)::int as bulan,
  count(*)::int as total_transaksi,
  coalesce(sum(total_harga), 0)::int as total_pendapatan,
  count(*) filter (where status = 'selesai')::int as selesai,
  count(*) filter (where status in ('pending', 'pending_payment'))::int as pending,
  count(*) filter (where status in ('lunas', 'paid'))::int as lunas,
  count(*) filter (where status = 'batal')::int as batal
from public.transaksi
group by extract(year from tanggal_transaksi), extract(month from tanggal_transaksi);

-- =========================
-- Function cek jumlah alat yang sedang terbooking pada rentang tanggal tertentu
-- Bisa dipakai backend untuk validasi stok rental.
-- =========================
create or replace function public.get_booked_quantity(
  p_id_alat bigint,
  p_tanggal_mulai date,
  p_tanggal_selesai date
)
returns integer
language sql
stable
as $$
  select coalesce(sum(dt.jumlah), 0)::int
  from public.detail_transaksi dt
  join public.transaksi t on t.id = dt.id_transaksi
  where dt.id_alat = p_id_alat
    and t.status in ('pending', 'lunas', 'pending_payment', 'paid', 'dipinjam')
    and t.tanggal_mulai < p_tanggal_selesai
    and t.tanggal_selesai > p_tanggal_mulai;
$$;

